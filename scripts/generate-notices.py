#!/usr/bin/env python3
"""Write THIRD-PARTY.md: the licenses of everything shipped in the release exe.

Crate licenses come from `cargo about` (config in about.toml); the Lucide icons embedded in
the exe are appended from assets/icons/lucide/LICENSE. The file is not committed: the release
workflow generates it and attaches it to the release. On dependency changes CI runs it only so
cargo-about fails on a license that about.toml does not accept.

    python scripts/generate-notices.py
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD-PARTY.md"
LUCIDE_LICENSE = ROOT / "assets" / "icons" / "lucide" / "LICENSE"

COPYRIGHT = re.compile(r"^\s*(?:#\s*)?Copyright\b.*$", re.MULTILINE)
# Unfilled license templates, e.g. "Copyright [yyyy] [name of copyright owner]".
PLACEHOLDER = re.compile(r"yyyy|<year>", re.IGNORECASE)

PREAMBLE = """# Third-party licenses

Razer Battery Report is licensed under the MIT License. It is built from the open-source
components listed below. Each section names the crates covered by one license and the copyright
notices they carry, followed by the license text.

This file is generated by `scripts/generate-notices.py`.
"""

LUCIDE_INTRO = """## Lucide icons

The tray icons are taken from Lucide. The notice below is the verbatim `LICENSE` of the Lucide
project, which also covers the icons it derived from Feather.
"""


def harvest():
    if not shutil.which("cargo-about"):
        sys.exit("notices: cargo-about missing, run `cargo install --locked cargo-about --features cli`")

    # cargo-about refuses redirected stdout under PowerShell, so it writes to a file.
    with tempfile.TemporaryDirectory() as folder:
        report = Path(folder) / "report.json"
        done = subprocess.run(
            ["cargo", "about", "generate", "--format", "json", "--output-file", str(report)],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        if done.returncode != 0:
            sys.exit(f"notices: cargo about failed: {done.stderr.strip()}")
        return json.loads(report.read_text(encoding="utf-8"))


def notices(text):
    seen = []
    for line in COPYRIGHT.findall(text):
        line = " ".join(line.split()).rstrip(".")
        if not PLACEHOLDER.search(line) and line not in seen:
            seen.append(line)
    return seen


def link(crate):
    name = crate["name"]
    url = crate.get("repository") or f"https://crates.io/crates/{name}"
    return f"[{name} {crate['version']}]({url})"


def collect(report):
    groups = {}
    for entry in report["licenses"]:
        group = groups.setdefault(entry["id"], {"name": entry["name"], "text": None, "users": {}})
        if group["text"] is None or entry.get("first_of_kind"):
            group["text"] = entry["text"]
        for use in entry["used_by"]:
            crate = use["crate"]
            if crate.get("source") is None:
                continue
            user = group["users"].setdefault(f"{crate['name']} {crate['version']}", {"crate": crate, "notices": []})
            for notice in notices(entry["text"]):
                if notice not in user["notices"]:
                    user["notices"].append(notice)
    return groups


def render(groups):
    out = [PREAMBLE]
    for license_id in sorted(groups):
        group = groups[license_id]
        if not group["users"]:
            continue
        out.append(f"## {group['name']}\n")
        out.append(f"Used by {len(group['users'])} crate(s):\n")
        for key in sorted(group["users"], key=str.lower):
            user = group["users"][key]
            line = f"- {link(user['crate'])}"
            if user["notices"]:
                line += " — " + "; ".join(user["notices"])
            out.append(line)
        out.append("")
        out.append("```text")
        out.append(dedent(group["text"]).strip("\n"))
        out.append("```\n")

    lucide = LUCIDE_LICENSE.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")
    out += [LUCIDE_INTRO, "```text", lucide, "```"]
    return "\n".join(out) + "\n"


def dedent(text):
    lines = text.replace("\r\n", "\n").split("\n")
    pad = min((len(line) - len(line.lstrip()) for line in lines if line.strip()), default=0)
    return "\n".join(line[pad:].rstrip() if line.strip() else "" for line in lines)


def main():
    OUTPUT.write_text(render(collect(harvest())), encoding="utf-8", newline="\n")
    print(f"notices: wrote {OUTPUT.name}")


if __name__ == "__main__":
    main()
